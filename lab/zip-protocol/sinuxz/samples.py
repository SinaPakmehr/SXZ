from __future__ import annotations

import os
import random
import struct
import zlib

from .models import _xorshift_step


def make_png(width: int, height: int) -> bytes:
    rows = bytearray()
    for y in range(height):
        rows.append(0)  # filter: none
        for x in range(width):
            rows += bytes(((x * 255) // max(width - 1, 1), (y * 255) // max(height - 1, 1), (x * y) & 0xFF))

    def chunk(tag: bytes, payload: bytes) -> bytes:
        return (
            struct.pack(">I", len(payload))
            + tag
            + payload
            + struct.pack(">I", zlib.crc32(tag + payload) & 0xFFFFFFFF)
        )

    ihdr = struct.pack(">IIBBBBB", width, height, 8, 2, 0, 0, 0)
    return (
        b"\x89PNG\r\n\x1a\n"
        + chunk(b"IHDR", ihdr)
        + chunk(b"IDAT", zlib.compress(bytes(rows), 9))
        + chunk(b"IEND", b"")
    )


def lfsr_bytes(nbytes: int, seed: int = 0xACE1) -> bytes:
    """Maximal-ish 32 bit Fibonacci LFSR, packed big endian."""
    taps = (1 << 31) | (1 << 21) | (1 << 1) | 1
    state = seed & 0xFFFFFFFF
    out = bytearray()
    for _ in range(nbytes):
        byte = 0
        for _ in range(8):
            bit = (state & taps).bit_count() & 1
            state = ((state >> 1) | (bit << 31)) & 0xFFFFFFFF
            byte = (byte << 1) | bit
        out.append(byte)
    return bytes(out)


def xorshift_bytes(nbytes: int, seed: int = 0xC0FFEE) -> bytes:
    state = seed
    out = bytearray()
    while len(out) < nbytes:
        state = _xorshift_step(state)
        out += bytes(((state >> 24) & 0xFF, (state >> 16) & 0xFF, (state >> 8) & 0xFF, state & 0xFF))
    return bytes(out[:nbytes])


