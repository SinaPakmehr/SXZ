def build_samples(out_dir: str) -> list[str]:
    os.makedirs(out_dir, exist_ok=True)
    rng = random.Random(20261125)
    files: dict[str, bytes] = {}

    text = (TEXT_EN * 3) + TEXT_FA
    files["text_1k.txt"] = text.encode("utf-8")[:1024]

    files["gradient_32x32.png"] = make_png(32, 32)
    files["counter_4k.bin"] = bytes(range(256)) * 16
    files["lfsr_4k.bin"] = lfsr_bytes(4096)
    files["xorshift_4k.bin"] = xorshift_bytes(4096)
    files["zeros_4k.bin"] = b"\x00" * 4096
    files["pattern_4k.bin"] = b"SINUX!" * 683 + b"SIN"
    files["random_1k.bin"] = bytes(rng.getrandbits(8) for _ in range(1024))
    files["mixed_4k.bin"] = b"\x00" * 1024 + text.encode("utf-8")[:1024] + bytes(
        rng.getrandbits(8) for _ in range(1024)
    ) + bytes(range(256)) * 4

    written = []
    for name, payload in files.items():
        path = os.path.join(out_dir, name)
        with open(path, "wb") as fh:
            fh.write(payload)
        written.append(path)
    with open(os.path.join(out_dir, "README.txt"), "w", encoding="utf-8") as fh:
        fh.write("Generated by `python -m sinuxz samples`. Deterministic, no external assets.\n")
    return written


