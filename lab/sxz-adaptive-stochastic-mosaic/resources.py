def worker(path):
    blob=Path(path).read_bytes();mem=ws();p={}
    (d,t)=run(a.decode,blob,None,p)
    ready={};assert a.decode(blob,ready)==d
    warm=[]
    for _ in range(7):
        u,j=run(a.decode,blob,ready)
        assert u==d
        warm.append(j)
    print(json.dumps(dict(cold_s=t,warm_s=median(warm),warm_trials=warm,before=mem,after=ws(),
        sha256=hashlib.sha256(d).hexdigest(),parallel=False,cold_generation_s=p["generation_s"],
        cache_entries=len(ready),cache_bytes=sum(map(len,ready.values())),input_bytes=len(d),
        package_versions=dict(zstandard=a.z.__version__,numpy=np.__version__))))


def resources():
    d,_=plant("shared"); vdata,_=plant("multi")
    syn=[]
    for name,data in (("shared",d),("multi",vdata)):
        with a.Bank([(0,0,np.arange(1024,dtype=np.uint32))],1536) as b:
            edges,_=b.search(data)
        groups=a.group_candidates(edges)
        use=a.dp([e for _,_,rs in groups[:4] for e in rs],True)[1]
        syn.append((name,data,a.arch(data,a.sequences(data,use),group=True,addr="affine")[0]))
    png=next(d for x,d in pick("dev") if x["name"]=="python-logo.png")
    syn.append(("PNG-direct",png,a.arch(png,a.sequences(png,[]),group=False)[0]))
    allrows=[]
    tmp=Path(__file__).resolve().parents[2]/"datasets/tools"
    with TemporaryDirectory() as td:
        p=Path(td)/"probe.asm"
        for k,s,b in syn:
            p.write_bytes(b)
            c=subprocess.run([sys.executable,"-B",str(a.ROOT/"resources.py"),"worker",str(p)],capture_output=True,
                             text=True,check=True,timeout=40)
            z=json.loads(c.stdout);assert z["sha256"]==hashlib.sha256(s).hexdigest()
            allrows.append(dict(name=k,archive_bytes=len(b),**z))
    pairs=[d for x,d in pick("dev") if x["name"] in ("gull.jpg","irs1040.pdf")]
    refs=[]
    def job(d):
        h,r=ix.search(d)
        return h,r["hits"],r["covered"]
    with a.Bank([(0,0,a.seeds(16))]) as ix,ThreadPoolExecutor(2) as pool:
        for _ in range(5):
            v,one=run(lambda:[job(x) for x in pairs])
            w,two=run(lambda:list(pool.map(job,pairs)))
            assert v==w
            refs.append(dict(one_s=one,two_s=two))
    save("resources",dict(rows=allrows,parallel_trials=refs,
         native_shared_DLL_bytes=Path(a.N._name).stat().st_size,
         asm_python_bytes=(a.ROOT/"asm.py").stat().st_size,
         shared_representation_py_bytes=(a.MS/"represent.py").stat().st_size,
         minimum_dependencies=["CPython","NumPy","zstandard","asm_native.dll","represent.py"]))


def ablation():
    rows=[]
    # Swap seed 0 for one new seed; keep generated bytes and positions fixed.
    # 4096 is intentionally allowed in this post-hoc diagnostic (13-bit value).
    with a.Bank([(0,0,np.arange(1,4097,dtype=np.uint32))]) as b:
        for p,d in load():
            h,st=b.search(d,cap=8000 if len(d)>4<<20 else 25000)
            q=trial(d,h)
            rows.append(dict(input=p,search=st,**q))
        save("without-zero",rows)


if __name__=="__main__":
    args=argparse.ArgumentParser()
    args.add_argument("mode",nargs="?",choices=["worker","resources","ablation"],default="resources")
    args.add_argument("file",nargs="?")
    x=args.parse_args()
    if x.mode=="worker":worker(x.file)
    else:globals()[x.mode]()
