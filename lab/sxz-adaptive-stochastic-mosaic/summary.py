"""Measured family, architecture, and whole-file tables plus reproducible SVG."""
import hashlib
import json
from collections import defaultdict
from pathlib import Path
from statistics import mean,median

import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt

ROOT=Path(__file__).resolve().parent
R=ROOT/"results"


def load(n): return json.loads((R/(n+".json")).read_text(encoding="utf-8"))


def report():
    d,h=load("dev"),load("heldout")
    c,r=load("control"),load("radix")
    stats=defaultdict(list)
    for x in h["rows"]:stats[x["bank"]].append(x)
    assert len(stats)==7 and all(len(row)==22 for row in stats.values())
    overview={}
    lines=[
        "# ASMC paired complete-file comparisons",
        "",
        "Bytes are actual serialized archive length. Same-splits stores the identical slices as literals in the metadata",
        "and holds the Zstd-coded remaining literal stream constant. Net means direct-frame bytes minus best tested candidate.",
        "",
        "## Full test, 393,216 generated bytes per bank",
        "| Bank | Files | Mean raw union % | Candidate slots with saturation | Best match | Files with genuine common groups | Positive vs direct | Gates passed | Net with fallback B |",
        "|---|---:|---:|---:|---:|---:|---:|---:|---:|"
    ]
    for k,v in stats.items():
        n=len(v)
        q=dict(files=n,input_bytes=sum(x["input"]["input_bytes"] for x in v),
               coverage=mean(x["search"]["covered"]/x["search"]["target_symbols"] for x in v),
               best=max(x["search"]["max"] for x in v),raw_hits=sum(x["search"]["hits"] for x in v),
               max_hits=max(x["search"]["hits"] for x in v),
               over_capacity=sum(x["search"]["dropped"]>0 for x in v),
               selected_share=mean(x["selected_coverage"] for x in v if x["net"]>0) if any(x["net"]>0 for x in v) else 0,
               files_positive=sum(x["net"]>0 for x in v),files_common_groups=sum(x["groups_exact_disjoint_at_least_two"]>0 for x in v),
               forced_net=sum(x["net"] for x in v),net_fallback=sum(max(0,x["net"]) for x in v),
               positive=[dict(file=x["input"]["name"],net=x["net"],isolated=x["isolated"],recipe=x["best"]) for x in v if x["net"]>0],
               gate=sum(min(x["isolated"],x["net"])>=128 and
                        min(x["isolated"],x["net"])*100>=x["methods"]["direct"]["bytes"] for x in v))
        overview[k]=q
        lines.append(f"| {k} | {n} | {100*q['coverage']:.5f} | {q['over_capacity']} | {q['best']} | "
                     f"{q['files_common_groups']} | {q['files_positive']} | {q['gate']} | {q['net_fallback']:,} |")
    lines.extend(["","## Held-out full files / adaptive uniform only",
           "| File | Original | A | B | C | Gain vs direct | Same-splits isolated gain | Baseline Zstd-3 | Best ordinary* | Prior MSMC hybrid fallback |",
           "|---|---:|---:|---:|---:|---:|---:|---:|---:|---:|"])
    for x in stats["adaptive-splitmix"]:
        n=x["input"]["name"];m=x["methods"];rr=h["references"][n]
        best=min(q.get("standalone_bytes",q["bytes"]) for q in rr.values())
        old=h["msmc"].get(n)
        lines.append(f"| {n} | {x['input']['input_bytes']:,} | {m['A']['bytes']:,} | {m['B']['bytes']:,} | {m['C']['bytes']:,} | "
                     f"{x['net']:,} | {x['isolated']:,} | {rr['zstd-3']['bytes']:,} | {best:,} | {old['fallback'] if old else '—'} |")
    lines.extend(["","* Traditional dictionary is charged standalone in this column. Standard timing rows for the 19 old exact",
           "inputs were reused SHA-for-SHA; timing for 3 new inputs was newly measured.",
           "","## Synthetic exact controls",
           "| Case | Input | Direct | A | B | C | Best route | Covered (%) | Isolated gain | C fallback-group count |",
           "|---|---:|---:|---:|---:|---:|---|---:|---:|---:|"])
    for x in c:
        m=x["methods"]
        lines.append(f"| {x['name']} | {x['file_bytes']} | {m['direct']['bytes']} | {m['A']['bytes']} | {m['B']['bytes']} | "
                     f"{m['C']['bytes']} | {x['best']} | {100*x['selected_coverage']:.3f} | {x['isolated']} | {m['C']['sources']} |")
    lines.extend(["","## Small representation panel","| Mode | File | Raw symbol union % | Longest symbols | Net B |",
                       "|---|---|---:|---:|---:|"])
    for x in r:lines.append(f"| {x['mode']} | {x['name']} | {100*x['search']['covered']/x['search']['target_symbols']:.4f} | "
                    f"{x['search']['max']} | {x['net']} |")
    (R/"tables.md").write_text("\n".join(lines)+"\n",encoding="utf-8")
    (R/"overview.json").write_text(json.dumps(overview,indent=2)+"\n",encoding="utf-8")
    images=R/"figures";images.mkdir(exist_ok=True)
    for k in ("coverage","net"):
        fig,ax=plt.subplots(figsize=(7.6,4.4))
        for model in list(dict.fromkeys(x["family"] for x in d)):
            widths=(8,12,16,20,24,32)
            data=[[x for x in d if x["family"]==model and x["bits"]==b] for b in widths]
            # Label the right-hand entries as sampled sizes, not complete 2^32.
            if k=="coverage":
                x=widths
                y=[mean(100*q["search"]["covered"]/q["search"]["target_symbols"] for q in xs) for xs in data]
                ax.set(xlabel="Nominal seed bits (20/24/32 sampled: 65,536)",ylabel="Mean raw byte coverage (%)",
                       title="Development: seed space vs coverage")
            else:
                x=[xs[0]["num_seeds"] for xs in data]
                y=[sum(q["net"] for q in xs) for xs in data]
                ax.set(xscale="log",xlabel="Actually generated seeds per bank",ylabel="Total net bytes vs direct frame",
                       title="Development: more seeds do not imply savings")
            ax.plot(x,y,"o-",label=model)
        ax.grid(alpha=.5,linestyle=":");ax.legend();fig.tight_layout()
        fig.savefig(images/(k+".svg"));plt.close(fig)
    refs=json.loads((ROOT/"prior-hashes.json").read_text(encoding="utf-8"))
    current={p:hashlib.sha256((ROOT.parent/p).read_bytes()).hexdigest() for p in refs}
    assert refs==current
    (R/"preservation.json").write_text(json.dumps(current,indent=2)+"\n",encoding="utf-8")
    rows=[*d,*h["rows"],*c,*r]
    for x in rows:
        for y in x["methods"].values():
            assert y["exact"] and y["bytes"]==sum(y[k] for k in ("header_bytes","meta_bytes","literals_bytes"))


if __name__=="__main__":report()
